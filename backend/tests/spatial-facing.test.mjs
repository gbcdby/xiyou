const epoch = Date.parse('2026-11-13T22:00:00Z');
const command = (r, destination) => ({ kind: 'move_to', movementCommandSeq: String(++r.actors.get(0).seq), sceneId: 'gaolao-courtyard', destination });
const saved = async (db, id) => (await db.pool.query('SELECT state FROM sessions WHERE session_id=$1', [id])).rows[0].state;

test('CUI-OBS-01 八向约定、末段拐弯及实际取整零位移', () => {
    const start = { x: 100, y: 100 };
    for (const [facing, x, y] of [['E', 110, 100], ['SE', 110, 110], ['S', 100, 110], ['SW', 90, 110], ['W', 90, 100], ['NW', 90, 90], ['N', 100, 90], ['NE', 110, 90]])
        assert.equal(facingAlongPath([start, { x, y }], 'S'), facing);
    const bent = [start, { x: 180, y: 100 }, { x: 180, y: 80 }, { x: 180, y: 80 }];
    assert.equal(facingAlongPath(bent, 'W'), 'N', '终点主要在东侧，站姿仍取最后北行段并跳过重复顶点');
    assert.equal(facingAlongPath([{ x: 680, y: 370 }, { x: 645, y: 285 }], 'S'), 'N', '实际路线终段在北向八分区内');
    assert.equal(facingAlongPath([{ x: 681, y: 370 }, { x: 645, y: 285 }], 'S'), 'NW', '边界另一侧属于西北');
    const quantized = pointAlongPath([start, { x: 110, y: 100 }], 0.49).position;
    assert.deepEqual(quantized, start);
    assert.equal(facingAlongPath([start, quantized], 'W'), 'W');
    assert.equal(facingAlongPath([start, start, start], 'NE'), 'NE');
    assert.equal(facingAlongPath([start], 'SW'), 'SW');
});

test('CUI-OBS-01 真实PG：朝向随已发生位移保存，接受目标、取整零位移、停止和拒绝不改站姿，重启保持', async t => {
    const db = await startTestPostgres('current-facing', { outputSubdirectory: 'cui-facing' }), clock = { value: epoch };
    let runtime = await createRuntime({ pool: db.pool, now: () => clock.value });
    t.after(async () => { await runtime.close(); await db.stop(); });
    const r = await gaolaoRoom(runtime, clock, 2, 'gaolaozhuang-scene-v2');
    await r.go(0, r.C('C18'));
    const id = (await runtime.replay(r.sessionId)).members[0].characterId;
    const before = (await runtime.replay(r.sessionId)).characters[id];
    accepted(await r.send(0, command(r, { x: 1100, y: 650 })));
    const plan = (await runtime.replay(r.sessionId)).characters[id];
    assert.equal(plan.facing, before.facing, '接受目标本身没有位移');
    await r.step(1);
    const rounded = (await runtime.replay(r.sessionId)).characters[id];
    assert.deepEqual(rounded.position, before.position);
    assert.equal(rounded.facing, before.facing);
    assert.equal(rounded.spatialRevision, plan.spatialRevision);
    await r.step(200);
    const moving = (await runtime.replay(r.sessionId)).characters[id];
    t.diagnostic(JSON.stringify({ checkpoint: '实际东移', position: moving.position, facing: moving.facing, spatialRevision: moving.spatialRevision }));
    assert.ok(moving.position.x > before.position.x);
    assert.equal(moving.facing, 'E');
    assert.equal(moving.spatialRevision, String(BigInt(plan.spatialRevision) + 1n));
    assert.equal(moving.resourceRevision, before.resourceRevision);
    assert.equal(moving.appearanceEpoch, before.appearanceEpoch);
    const stop = accepted(await r.send(0, { kind: 'stop_move', movementCommandSeq: String(++r.actors.get(0).seq) }));
    await r.step(1000);
    const stopped = (await runtime.replay(r.sessionId)).characters[id];
    assert.deepEqual(stopped.position, moving.position);
    assert.equal(stopped.facing, 'E');
    assert.equal(stopped.movement.status, 'cancelled');
    assert.equal(stopped.spatialRevision, moving.spatialRevision);
    assert.equal((await r.send(0, command(r, { x: 0, y: 0 }))).status, 'Rejected');
    assert.equal((await runtime.replay(r.sessionId)).characters[id].facing, 'E');
    accepted(await r.send(0, command(r, stopped.position)));
    const zeroPlan = (await runtime.replay(r.sessionId)).characters[id];
    await r.step(1000);
    const final = await runtime.replay(r.sessionId);
    assert.deepEqual(final.characters[id].position, stopped.position);
    assert.equal(final.characters[id].facing, 'E');
    assert.equal(final.characters[id].spatialRevision, zeroPlan.spatialRevision, '保留受理计划原有版本变化，零位移检查点不另增版本');
    assert.equal((await r.snapshot(0)).projection.self.facing, 'E');
    assert.deepEqual(await saved(db, r.sessionId), final);
    await runtime.close();
    runtime = await createRuntime({ pool: db.pool, now: () => clock.value });
    const recovered = await runtime.replay(r.sessionId), cold = await runtime.snapshot(r.users[0].token, r.sessionId, ['spatial-v2']);
    assert.equal(recovered.characters[id].facing, 'E');
    assert.deepEqual(recovered.characters[id].position, stopped.position);
    assert.equal(cold.projection.self.facing, 'E');
    assert.equal(cold.projection.self.motionTrail, undefined);
    assert.deepEqual(await runtime.receipt(r.users[0].token, r.sessionId, stop.clientActionId), stop);
});

test('CUI-OBS-01 真实PG：单次检查点跨过拐点，取最后实际北行段而非起终点西向合成', async t => {
    const db = await startTestPostgres('corner-facing', { outputSubdirectory: 'cui-facing' }), clock = { value: epoch };
    const runtime = await createRuntime({ pool: db.pool, now: () => clock.value });
    t.after(async () => { await runtime.close(); await db.stop(); });
    const r = await gaolaoRoom(runtime, clock, 2, 'gaolaozhuang-scene-v2');
    await r.go(0, r.C('C01'));
    const id = (await runtime.replay(r.sessionId)).members[0].characterId;
    accepted(await r.send(0, command(r, r.C('C12').position)));
    const before = await runtime.replay(r.sessionId), a = before.characters[id], path = a.movement.path;
    assert.ok(path.length > 2, '本次真实寻路必须含有拐点');
    const last = path.at(-1), prior = path.at(-2);
    assert.deepEqual(prior, { x: 680, y: 370 });
    assert.deepEqual(last, { x: 645, y: 285 });
    assert.ok(Math.abs(last.x - a.position.x) > Math.abs(last.y - a.position.y) * 3, '全程合成方向为西，不能代替最终北行段');
    await r.step(6000);
    const current = (await runtime.replay(r.sessionId)).characters[id];
    t.diagnostic(JSON.stringify({ path, oldPosition: a.position, actualPosition: current.position, facing: current.facing }));
    assert.equal(current.movement.status, 'arrived');
    assert.deepEqual(current.position, last);
    assert.equal(current.facing, 'N');
    assert.equal(current.spatialRevision, String(BigInt(a.spatialRevision) + 1n));
    const updates = (await db.pool.query("SELECT event FROM world_events WHERE session_id=$1 AND session_seq>$2 AND event->>'kind'='spatial.actor' AND event->'payload'->'actor'->>'characterId'=$3", [r.sessionId, before.sessionSeq, id])).rows;
    assert.equal(updates.length, 1, '朝向与位置共用原有单条角色事件');
    assert.equal(updates[0].event.payload.actor.facing, 'N');
});

test('CUI-OBS-01 真实PG旧v1受信fixture：随行最后北行段持久，原地等待不改朝向或空间版本', async t => {
    const db = await startTestPostgres('legacy-follow-facing', { outputSubdirectory: 'cui-facing' }), clock = { value: epoch };
    const runtime = await createRuntime({ pool: db.pool, now: () => clock.value });
    t.after(async () => { await runtime.close(); await db.stop(); });
    const r = await gaolaoRoom(runtime, clock, 2, 'gaolaozhuang-v1');
    await openDoor(r); await startFollow(r);
    for (const at of ['C01', 'C13', 'C11']) await r.go(0, r.C(at));
    for (let i = 0; i < 5; i++) await r.step(1000);
    const id = r.content.chapterRules.people.cuilan, before = await runtime.replay(r.sessionId), a = before.characters[id];
    assert.equal(before.chapter.follows[id].policyRoute, undefined, '明确覆盖旧v1分支，不冒充生产scene自治');
    assert.deepEqual(a.position, { ...r.C('C11').position });
    t.diagnostic(JSON.stringify({ branch: 'legacy-v1', position: a.position, facing: a.facing }));
    assert.equal(a.facing, 'N');
    await r.step(1);
    const after = await runtime.replay(r.sessionId);
    assert.equal(after.characters[id].facing, 'N');
    assert.equal(after.characters[id].spatialRevision, a.spatialRevision);
    assert.equal((await r.snapshot('cuilan')).projection.self.facing, 'N');
    assert.deepEqual((await saved(db, r.sessionId)).characters[id], after.characters[id]);
});

test('CUI-OBS-01 真实PG/HTTP/Socket生产scene：本人自治随行提交北向，稳定等待不新增策略评估', async t => {
    const db = await startTestPostgres('policy-follow-facing', { outputSubdirectory: 'cui-facing' }), clock = { value: epoch };
    const server = await createAuthorityServer({ pool: db.pool, now: () => clock.value });
    let r;
    t.after(async () => { await r?.network.close(); await server.close(); await db.stop(); });
    r = await scenePolicyRoom(server, clock);
    await openSceneDoor(r); await r.propose('front-guest-room');
    for (const at of ['C01', 'C13', 'C11']) await r.go(0, r.C(at));
    for (let i = 0; i < 5; i++) await r.step(1000);
    const id = r.content.chapterRules.people.cuilan, before = await r.state(), a = before.characters[id];
    assert.ok(before.chapter.follows[id].policyRoute?.acceptance, '原生产本人已接受的路线关联');
    assert.deepEqual(a.position, { ...r.C('C11').position });
    t.diagnostic(JSON.stringify({ branch: 'scene-policy', position: a.position, facing: a.facing, evaluations: r.sceneStatus().evaluations }));
    assert.equal(a.facing, 'N');
    const evaluations = r.sceneStatus().evaluations;
    for (let i = 0; i < 3; i++) await r.step(50);
    const after = await r.state();
    assert.equal(after.characters[id].facing, 'N');
    assert.equal(after.characters[id].spatialRevision, a.spatialRevision);
    assert.equal((await r.snapshot('cuilan')).projection.self.facing, 'N');
    assert.equal((await r.entity(0, '翠兰')).facing, 'N');
    assert.equal(r.sceneStatus().evaluations, evaluations);
    assert.deepEqual((await saved(db, r.sessionId)).characters[id], after.characters[id]);
    assert.deepEqual(r.network.errors, []);
});
